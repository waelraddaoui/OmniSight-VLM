from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import List, Optional, Tuple, Dict, Any
from pydantic import BaseModel, Field


class AlertSeverity(str, Enum):
    INFO = "INFO"
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


@dataclass
class BoundingBox:
    """Represents a 2D bounding box in pixel coordinates (xyxy format)."""
    x1: float
    y1: float
    x2: float
    y2: float

    @property
    def width(self) -> float:
        return max(0.0, self.x2 - self.x1)

    @property
    def height(self) -> float:
        return max(0.0, self.y2 - self.y1)

    @property
    def area(self) -> float:
        return self.width * self.height

    @property
    def center(self) -> Tuple[float, float]:
        return ((self.x1 + self.x2) / 2.0, (self.y1 + self.y2) / 2.0)

    @property
    def bottom_center(self) -> Tuple[float, float]:
        """Useful as the 'ground contact point' for pedestrians and vehicles."""
        return ((self.x1 + self.x2) / 2.0, self.y2)

    def to_xyxy(self) -> Tuple[float, float, float, float]:
        return (self.x1, self.y1, self.x2, self.y2)

    def to_xywh(self) -> Tuple[float, float, float, float]:
        return (self.x1, self.y1, self.width, self.height)


@dataclass
class Detection:
    """A single object detection output from the detector."""
    bbox: BoundingBox
    class_name: str
    confidence: float
    class_id: int = 0
    mask: Optional[Any] = None  # Optional binary mask for instance segmentation


@dataclass
class TrackedObject:
    """An object tracked across consecutive frames with temporal history."""
    track_id: int
    class_name: str
    current_bbox: BoundingBox
    confidence: float
    trajectory: List[Tuple[float, float]] = field(default_factory=list)  # [(x, y), ...]
    first_seen_timestamp: float = 0.0
    last_seen_timestamp: float = 0.0
    total_frames_active: int = 1
    current_zone: Optional[str] = None
    time_in_current_zone: float = 0.0


class IncidentReport(BaseModel):
    """Structured reasoning output generated by the VLM for triggered events."""
    event_type: str = Field(description="Brief title of the observed event, e.g. 'Safety Perimeter Breach'")
    severity: AlertSeverity = Field(description="Assessed severity level of the incident")
    target_object_id: Optional[int] = Field(default=None, description="Track ID of the primary entity involved")
    description: str = Field(description="Concise factual description of what occurred based on visual evidence")
    recommended_action: str = Field(description="Recommended immediate corrective or supervisory action")
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
